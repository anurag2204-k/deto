export function getTodayDayKey(): string {
  const dayIndex = new Date().getDay(); // 0 = Sunday, 1 = Monday, ...
  const mapping = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
  return mapping[dayIndex] || 'monday';
}

export function getAllGymExercises(): GymExercise[] {
  return GYM_SCHEDULE.flatMap((day) => day.exercises);
}

export function findGymExercise(id: string): GymExercise | undefined {
  return getAllGymExercises().find((ex) => ex.id === id);
}
